def fetch_frame(term: str, source: str, token: str) -> list[dict]:
    """The rows production returns for one search term, in rank order."""
    query = urllib.parse.urlencode(
        {"name": term, "source": source, "limit": LIMIT}
    )
    request = urllib.request.Request(
        f"{API_BASE}{ENDPOINT}?{query}",
        headers={"Authorization": f"Bearer {token}"},
    )
    with urllib.request.urlopen(request, timeout=60) as response:
        if response.status != 200:
            raise RuntimeError(f"{term!r}: HTTP {response.status}")
        return json.loads(response.read())


def main() -> int:
    token = os.environ.get("API_TOKEN")
    if not token:
        print("API_TOKEN is required", file=sys.stderr)
        return 1

    wanted = sorted(
        {
            (case.get("source", DEFAULT_SOURCE), term)
            for case in CASES
            for term in case["terms"]
        }
    )
    # Keyed by source then term: the same term can be searched against two
    # sources, and the frames are not interchangeable.
    frames: dict[str, dict[str, list[dict]]] = {}
    for source, term in wanted:
        rows = fetch_frame(term, source, token)
        frames.setdefault(source, {})[term] = rows
        print(f"{source} {term!r}: {len(rows)} row(s)", file=sys.stderr)

    OUTPUT.write_text(
        json.dumps(
            {
                "metadata": {
                    "recorded_at": datetime.now(UTC).strftime("%Y-%m-%d"),
                    "api_base": API_BASE,
                    "endpoint": ENDPOINT,
                    "default_source_filter": DEFAULT_SOURCE,
                    "limit": LIMIT,
                    "note": (
                        "Source-narrowed frames, matching what the geocoder "
                        "searches for a place carrying an area_type (see each "
                        "case's `source`). NOT the unfiltered GET /api/aois "
                        "view a frontend caller sees."
                    ),
                    "cohort": (
                        "gnw-gold-evals cases/challenge/aoi/designations"
                    ),
                },
                "cases": CASES,
                "frames": frames,
            },
            indent=2,
            ensure_ascii=False,
            sort_keys=False,
        )
        + "\n",
        encoding="utf-8",
    )
    print(f"wrote {OUTPUT} ({OUTPUT.stat().st_size} bytes)", file=sys.stderr)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
