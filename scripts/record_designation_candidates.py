"""Record production AOI candidate frames for the PZB-1392 designation cohort.

The local dev database holds GADM only, so the protected-area rows this bug is
about cannot be reproduced offline. This script records what production
retrieval actually returns for each search term of the ``aoi/designations``
CHALLENGE cohort, so the scorer can be regression-tested against real frames in
a plain unit test -- no database, no LLM, no network at test time.

Fidelity note: the geocoder narrows its search to one source when the extracted
place carries an ``area_type`` (``_resolve_place`` in
``src/agent/subagents/pick_aoi/tool.py``), and only retries every source when
the narrowed frame comes back empty. Every frame here is therefore recorded
against the source that case's designation implies -- ``wdpa`` for a park or
reserve, ``landmark`` for an Indigenous territory. They are NOT what
``GET /api/aois`` shows a frontend caller with no source filter, and the
metadata block in the output says so.

The two terms per prompt are hand-written to the rules in
``src/agent/subagents/pick_aoi/prompts.py`` (``place`` keeps the designation and
is de-accented English; ``canonical`` drops the designation and restores the
official spelling). They are deliberately NOT generated by calling the model:
the fixture has to be deterministic, and the extraction step is not what this
bug is about.

Usage::

    API_TOKEN=... uv run python scripts/record_designation_candidates.py

Writes ``tests/fixtures/aoi_designation_candidates_v1.json``.
"""

